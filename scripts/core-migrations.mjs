#!/usr/bin/env node
// Copies the backend's SQLite migrations into the native core as plain SQL.
//
// The Node backend and the C++ core share one archivist.db while the backend is
// being ported, so their migrations must stay identical. This script replays
// backend/dist/database/migrations.js against a recording stand-in for
// better-sqlite3 and writes one .sql file per schema version.
//
//   node scripts/core-migrations.mjs          regenerate the SQL files
//   node scripts/core-migrations.mjs --check  fail when they have drifted

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "backend/dist/database/migrations.js");
const outputDirectory = path.join(
  root,
  "frontend/src/Core/Database/Migrations",
);
const checkOnly = process.argv.includes("--check");

if (!fs.existsSync(sourcePath)) {
  console.error("Build the backend first: npm run build -w backend");
  process.exit(1);
}

const { runMigrations } = await import(pathToFileURL(sourcePath).href);

const recorded = [];
let pending = { statements: [], foreignKeysDisabled: false, checkForeignKeys: false };
let foreignKeysOn = true;

const recorder = {
  exec(sql) {
    pending.statements.push(sql);
  },
  pragma(statement) {
    const text = String(statement).trim();

    if (text === "user_version") {
      return 0;
    }

    if (text === "foreign_keys") {
      return foreignKeysOn ? 1 : 0;
    }

    if (text === "foreign_keys = OFF") {
      foreignKeysOn = false;
      pending.foreignKeysDisabled = true;
      return undefined;
    }

    if (text === "foreign_keys = ON") {
      foreignKeysOn = true;
      return undefined;
    }

    if (text === "foreign_key_check") {
      pending.checkForeignKeys = true;
      return [];
    }

    const version = /^user_version\s*=\s*(\d+)$/.exec(text);

    if (version) {
      recorded.push({ version: Number(version[1]), ...pending });
      pending = {
        statements: [],
        foreignKeysDisabled: false,
        checkForeignKeys: false,
      };
      return undefined;
    }

    throw new Error(`Unexpected pragma in migrations: ${text}`);
  },
  transaction(callback) {
    return () => callback();
  },
};

runMigrations(recorder);

function dedent(sql) {
  const lines = sql.replace(/\r\n?/g, "\n").split("\n");
  const indents = lines
    .filter((line) => line.trim().length > 0)
    .map((line) => line.match(/^ */)[0].length);
  const indent = indents.length > 0 ? Math.min(...indents) : 0;

  return lines
    .map((line) => line.slice(indent).replace(/\s+$/, ""))
    .join("\n")
    .trim();
}

const expected = new Map();
const manifest = {
  generatedBy: "scripts/core-migrations.mjs",
  latestVersion: Math.max(...recorded.map((migration) => migration.version)),
  migrations: [],
};

for (const migration of recorded) {
  const fileName = `${String(migration.version).padStart(4, "0")}.sql`;
  const header =
    `-- Schema version ${migration.version}.\n` +
    "-- Generated by scripts/core-migrations.mjs from backend/src/database/migrations.ts. Do not edit.\n\n";

  expected.set(
    fileName,
    header + migration.statements.map(dedent).join("\n\n") + "\n",
  );
  manifest.migrations.push({
    version: migration.version,
    file: fileName,
    foreignKeysDisabled: migration.foreignKeysDisabled,
    checkForeignKeys: migration.checkForeignKeys,
  });
}

expected.set("migrations.json", JSON.stringify(manifest, null, 2) + "\n");

const actualFiles = fs.existsSync(outputDirectory)
  ? fs.readdirSync(outputDirectory).filter((name) => /\.(sql|json)$/.test(name))
  : [];

if (checkOnly) {
  const problems = [];

  for (const [name, content] of expected) {
    const filePath = path.join(outputDirectory, name);

    if (!fs.existsSync(filePath)) {
      problems.push(`missing ${name}`);
    } else if (fs.readFileSync(filePath, "utf8") !== content) {
      problems.push(`out of date ${name}`);
    }
  }

  for (const name of actualFiles) {
    if (!expected.has(name)) {
      problems.push(`unexpected ${name}`);
    }
  }

  if (problems.length > 0) {
    console.error("Core migrations have drifted from the backend:");
    for (const problem of problems) {
      console.error(`  ${problem}`);
    }
    console.error("Run: node scripts/core-migrations.mjs");
    process.exit(1);
  }

  console.log(`Core migrations match the backend (v${manifest.latestVersion}).`);
} else {
  fs.mkdirSync(outputDirectory, { recursive: true });

  for (const [name, content] of expected) {
    fs.writeFileSync(path.join(outputDirectory, name), content);
  }

  console.log(
    `Wrote ${recorded.length} migrations (v${manifest.latestVersion}) to ${path.relative(root, outputDirectory)}.`,
  );
}
