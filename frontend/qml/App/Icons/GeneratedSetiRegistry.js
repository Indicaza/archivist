function glyph(name) {
    return glyphs[String(name || "")] || ""
}

function color(name, tone) {
    var requestedTone = String(tone || "brand")
    if (requestedTone !== "brand") {
        return toneColors[requestedTone] || toneColors.muted
    }
    return brandColors[String(name || "")] || toneColors.normal
}
